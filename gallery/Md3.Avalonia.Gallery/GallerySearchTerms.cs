    internal static string For(string title) => Keywords.TryGetValue(title, out var keywords) ? keywords : string.Empty;

    internal static bool Matches(string title, string query, string? visibleTitle = null)
    {
        if (string.IsNullOrWhiteSpace(query)) return true;
        var keywords = For(title);
        var chineseTitle = GalleryLocalization.Translate(title, Chinese);
        return query.Split(' ', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .All(term => title.Contains(term, StringComparison.OrdinalIgnoreCase) ||
                         chineseTitle.Contains(term, StringComparison.OrdinalIgnoreCase) ||
                         keywords.Contains(term, StringComparison.OrdinalIgnoreCase) ||
                         visibleTitle?.Contains(term, StringComparison.OrdinalIgnoreCase) == true);
    }
